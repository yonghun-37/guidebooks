import {chromium} from '/tmp/ai-insta-phase3-browser/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'/home/yonghun/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({reducedMotion:'reduce'}), checks=[], errors=[];
const base=process.env.SITE_URL||'http://127.0.0.1:8594/site-shorts/chapters/';
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
try {
 await page.goto(base+'01-map.html');
 check('제작 순서 도구 존재',await page.locator('#pipeline-tool').count()===1);
 await page.locator('#material').selectOption('voice');
 check('빠진 녹음 설명',/녹음/.test(await page.locator('#pipeline-result').innerText()));
 await page.locator('#stage').selectOption('sound');
 check('소리 단계 재료 안내',/녹음/.test(await page.locator('#stage-note').innerText()));
 await page.locator('#material').selectOption('none');
 check('재료 복구',/재료/.test(await page.locator('#pipeline-result').innerText()));
 await page.goto(base+'03-hook.html');
 const art=await page.locator('#hook-drawing').innerHTML();
 await page.locator('#hook-choice').selectOption('specific');
 check('문장만 바뀜',art===await page.locator('#hook-drawing').innerHTML());
 check('구체 문장',/케이블/.test(await page.locator('#hook-line').innerText()));
 await page.locator('#hook-time').focus(); await page.keyboard.press('End');
 check('키보드 끝 프레임',await page.locator('#hook-time').inputValue()==='3');
 await page.locator('#hook-play').click(); await page.waitForTimeout(180);
 check('재생 진행',Number(await page.locator('#hook-time').inputValue())>0);
 await page.locator('#hook-play').click();
 check('재생 정지',await page.locator('#hook-play').getAttribute('aria-pressed')==='false');
 await page.goto(base+'04-script.html');
 await page.locator('#script-text').fill('가'.repeat(120));
 await page.locator('#sample-chars').fill('60'); await page.locator('#sample-seconds').fill('10');
 await page.locator('#pause-seconds').fill('2');
 check('120 / (60 / 10) + 2 = 22초',/22\.0초/.test(await page.locator('#script-result').innerText()));
 for(const [id,value] of [['sample-seconds','0'],['sample-seconds',''],['sample-chars','-1'],['pause-seconds','-1']]) {
  await page.locator('#sample-chars').fill('60');await page.locator('#sample-seconds').fill('10');await page.locator('#pause-seconds').fill('2');
  await page.locator('#'+id).fill(value);
  const output=await page.locator('#script-result').innerText();
  check('무효 입력 '+id+':'+value,/확인/.test(output)&&!output.includes('22.0초'));
 }
 await page.locator('#script-empty').click();
 check('빈 대본',/0\.0초/.test(await page.locator('#script-result').innerText()));
 await page.goto(base+'05-audio.html');
 check('자동 재생 없음',await page.locator('#audio-play').getAttribute('aria-pressed')==='false');
 await page.locator('#music-loud').click();
 check('극단값 음악 우세',/배경음/.test(await page.locator('#audio-result').innerText()));
 await page.locator('#voice-solo').click();
 check('음성 솔로',/내레이션만/.test(await page.locator('#audio-state').innerText()));
 await page.locator('#voice-mute').click();
 check('솔로 트랙 뮤트는 무음',/무음/.test(await page.locator('#audio-state').innerText()));
 await page.locator('#audio-reset').click();
 check('상태 초기화',await page.locator('#voice-solo').getAttribute('aria-pressed')==='false');
 await page.locator('#audio-play').focus(); await page.keyboard.press('Enter');
 check('키보드 소리 재생',await page.locator('#audio-play').getAttribute('aria-pressed')==='true');
 check('오디오 실제 실행',await page.evaluate(()=>window.audioLessonState?.contextState==='running'));
 await page.locator('#audio-play').click();
 check('소리 정지',await page.locator('#audio-play').getAttribute('aria-pressed')==='false');
 check('콘솔 오류 0',errors.length===0);
 console.log(JSON.stringify({checks:checks.length,passed:checks,errors},null,2));
 await fs.writeFile('docs/results/phase-Y4a/tools-check.json',JSON.stringify({checks:checks.length,passed:checks,errors},null,2)+'\n');
} finally {await browser.close();}
